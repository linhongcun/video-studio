#!/usr/bin/env python3
"""Natural Earth 1:110m land (public domain) -> equirectangular SVG asset + TS path module.
Source: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
Coordinates: x = lon + 180 (0..360), y = 90 - lat (0..180); 1 unit = 1 degree. Rings closed with Z, fill-rule evenodd.
Usage: python3 scripts/build-land.py   (reads data/ne_110m_land.geojson)"""
import json,hashlib
src='data/ne_110m_land.geojson';G=json.load(open(src))
def ring(r):
  pts=[f"{round(lon+180,2):g},{round(90-lat,2):g}" for lon,lat in r]
  return 'M'+'L'.join(pts)+'Z'
parts=[]
for f in G['features']:
  g=f['geometry'];polys=[g['coordinates']] if g['type']=='Polygon' else g['coordinates']
  for p in polys: parts+= [ring(r) for r in p]
d=''.join(parts);sha=hashlib.sha256(open(src,'rb').read()).hexdigest()[:8]
open('public/assets/ne_110m_land.svg','w').write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 360 180" width="3600" height="1800"><!-- Made with Natural Earth (public domain). ne_110m_land.geojson sha8 {sha}; equirectangular, x=lon+180, y=90-lat --><path fill="#1F2937" fill-rule="evenodd" d="{d}"/></svg>\n')
open('src/components/worldLand.ts','w').write(f'// GENERATED by scripts/build-land.py from Natural Earth 1:110m land (public domain), geojson sha8 {sha}.\n// Equirectangular: x = lon + 180, y = 90 - lat (degrees). Same path as public/assets/ne_110m_land.svg.\nexport const LAND_PATH = {json.dumps(d)};\nexport const LAND_SOURCE_SHA8 = {json.dumps(sha)};\n')
print(len(parts),'rings',len(d),'chars',sha)
