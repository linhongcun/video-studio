// Generate inline SVG assets and a timing snapshot from the authoritative storyboard.
// Run before typecheck/still/render; assets.gen.ts is intentionally gitignored.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const episode = path.join(here, '..');
const dir = path.join(episode, 'assets');
const storyboard = JSON.parse(fs.readFileSync(path.join(episode, 'storyboard.json'), 'utf8'));
const shots = storyboard.scenes.flatMap((scene) => scene.shots);
const files = fs.readdirSync(dir).filter((file) => file.endsWith('.svg')).sort();
const assets = Object.fromEntries(files.map((file) => [`assets/${file}`, fs.readFileSync(path.join(dir, file), 'utf8')]));
let end = 0;
for (const shot of shots) {
  if (shot.from !== end || !Number.isInteger(shot.durationInFrames) || shot.durationInFrames <= 0) {
    throw new Error(`Invalid shot timing: ${shot.id}`);
  }
  end += shot.durationInFrames;
  for (const element of shot.elements) {
    if (!['rect', 'text', 'line', 'image'].includes(element.type)) throw new Error(`Unsupported element type: ${element.type}`);
    if (element.asset && !Object.hasOwn(assets, element.asset)) throw new Error(`Missing SVG: ${shot.id}/${element.asset}`);
  }
}
if (end !== storyboard.meta.durationInFrames) throw new Error(`Shot sum ${end} differs from storyboard total`);
fs.writeFileSync(path.join(here, 'src/assets.gen.ts'),
  `// Generated by sync_assets.mjs; do not edit.\nconst ASSETS: Record<string, string> = ${JSON.stringify(assets, null, 1)};\nexport default ASSETS;\n`);
const timing = Object.fromEntries(shots.map((shot) => [shot.id, {
  from: shot.from, duration: shot.durationInFrames, chapter: shot.chapterId,
  noAudio: !!shot.chapterCard,
}]));
fs.writeFileSync(path.join(here, 'src/timing.json'), JSON.stringify(timing, null, 2) + '\n');
console.log(`assets.gen.ts: ${files.length} SVGs; timing.json: ${shots.length} shots, ${end} frames`);
