#!/usr/bin/env python3
"""Validate the physical series layout; --write-index refreshes its README."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import shlex
import sys


ROOT = Path(__file__).resolve().parents[1]
KEY = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")
MARKER = "<!-- Generated by scripts/check-layout.py --write-index. -->"


def read(file):
    return json.loads(file.read_text(encoding="utf-8"))


def validate():
    base = ROOT / "episodes"
    catalog = read(ROOT / "site/src/content/series.json")
    if (ROOT / "episodes-codex").exists() or (ROOT / "series").exists():
        raise ValueError("Use the unified episodes/<series>/<slug>/ directories")
    episodes = []
    seen = set()
    for series in sorted(base.iterdir()):
        if series.name.startswith("_") or series.name == "README.md":
            continue
        if series.is_symlink() or not series.is_dir() or series.name not in catalog:
            raise ValueError(f"Unexpected series directory: {series.relative_to(ROOT)}")
        for episode in sorted(series.iterdir()):
            slug = episode.name
            if episode.is_symlink() or not episode.is_dir() or not KEY.fullmatch(slug) or slug in seen:
                raise ValueError(f"Invalid or duplicate episode: {episode.relative_to(ROOT)}")
            seen.add(slug)
            for purpose in ("production", "publication"):
                directory = episode / purpose
                if directory.is_symlink() or not directory.is_dir():
                    raise ValueError(f"Expected a real {purpose} directory: {episode.relative_to(ROOT)}")
            metadata = read(episode / "publication/meta.json")
            if metadata.get("series") != series.name:
                raise ValueError(f"{slug}: meta.series must match its directory")
            source = metadata.get("sourcePath")
            if not isinstance(source, str) or Path(source).is_absolute():
                raise ValueError(f"{slug}: sourcePath must be repository-relative")
            source = (ROOT / source).resolve()
            if not source.is_dir() or not source.is_relative_to(episode / "production"):
                raise ValueError(f"{slug}: sourcePath must locate its real production source")
            for field in ("video", "poster"):
                value = metadata.get(field)
                if not value and metadata.get("draft"):
                    continue
                if not isinstance(value, str):
                    raise ValueError(f"{slug}: missing {field}")
                media = (episode / "publication" / value).resolve()
                if not media.is_file() or not media.is_relative_to(episode / "publication"):
                    raise ValueError(f"{slug}: {field} must be a local publication file")
            episodes.append((series.name, slug, metadata))
    if not episodes:
        raise ValueError("No episodes found")
    # The template is pasted into production/remotion/package.json. Check its
    # real execution base so a directory move cannot silently break new work.
    first_series, first_slug, _ = episodes[0]
    cwd = base / first_series / first_slug / "production/remotion"
    template = read(base / "_template/reference-scripts.json")
    for name, command in template["scripts"].items():
        arguments = shlex.split(command)
        if arguments[0] in {"node", "python3"} and not (cwd / arguments[1]).is_file():
            raise ValueError(f"New-episode template {name} points to a missing script")
        if "--bgm" in arguments and not (cwd / arguments[arguments.index("--bgm") + 1]).is_file():
            raise ValueError(f"New-episode template {name} points to missing music")
    return catalog, episodes


def index(catalog, episodes):
    rows = [MARKER, "# 视频工程", "",
            "制作源码和站点发布资料按系列、视频集中存放在真实目录中。", "",
            "```text", "episodes/", "  <series>/<slug>/",
            "    production/    文稿、配音、动画工程、修订与冻结证据",
            "    publication/   元数据、文章、成片、字幕与封面",
            "  _shared/         统一的配音、动画、封面、冻结和渲染工具",
            "  _template/       新期模板", "```", "",
            "当前动画修订以各期 `publication/meta.json.sourcePath` 为准。"
            "线上页面与媒体 URL 继续使用原 slug。", "",
            "| 系列 | 视频数（含历史回看） |", "| --- | ---: |"]
    for key in sorted(catalog, key=lambda key: (catalog[key].get("order", 99), key)):
        count = sum(series == key for series, _, _ in episodes)
        if count:
            rows.append(f"| [{catalog[key]['title']}]({key}/) | {count} |")
    rows.extend(["", f"共 {len(episodes)} 期。新增或调整归属后执行：", "",
                 "```sh", "python3 scripts/check-layout.py --write-index",
                 "python3 scripts/check-layout.py", "```", "",
                 "[制作流程](../docs/pipeline.md) · [迁移说明与历史路径映射]"
                 "(../docs/archive/2026-11/episode-layout/README.md)", ""])
    return "\n".join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-index", action="store_true")
    args = parser.parse_args()
    try:
        catalog, episodes = validate()
        expected = index(catalog, episodes)
        file = ROOT / "episodes/README.md"
        if args.write_index:
            if file.exists() and not file.read_text(encoding="utf-8").startswith(MARKER):
                raise ValueError("Refusing to overwrite a hand-written episodes/README.md")
            file.write_text(expected, encoding="utf-8")
        elif not file.is_file() or file.read_text(encoding="utf-8") != expected:
            raise ValueError("Episode index is stale; run python3 scripts/check-layout.py --write-index")
        print(f"Episode layout passed: {len(episodes)} real production/publication pairs, "
              f"{len({key for key, _, _ in episodes})} series; current source paths and media exist.")
        return 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Episode layout failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
