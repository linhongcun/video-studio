"""Project Natural Earth land into a local SVG path module, without remote rendering.

Equirectangular Pacific view: lon 55..255, lat -5..75, 7.5px/degree.
Unwrap each ring continuously, then repeat +/-360 so the viewport can clip at
the dateline without turning Asia/North America into an invented polygon.
"""
from pathlib import Path
import hashlib,json

D=Path(__file__).resolve().parent
raw=(D/'source/land-110m.geojson').read_bytes()
source=json.loads(raw)
paths=[]
for feature in source['features']:
    g=feature['geometry']
    polygons=[g['coordinates']] if g['type']=='Polygon' else g['coordinates']
    for polygon in polygons:
        for shift in [-360,0,360]:
            pieces=[]
            for ring in polygon:
                unwrapped=[]
                for lon,lat in ring:
                    if not unwrapped:
                        while lon < 55: lon+=360
                        while lon >= 415: lon-=360
                    else:
                        while lon-unwrapped[-1][0] > 180: lon-=360
                        while lon-unwrapped[-1][0] < -180: lon+=360
                    unwrapped.append((lon,lat))
                xs=[lon+shift for lon,lat in unwrapped]
                ys=[lat for lon,lat in unwrapped]
                if max(xs)<55 or min(xs)>255 or max(ys)<-5 or min(ys)>75: continue
                points=[(210+(lon+shift-55)*7.5,290+(75-lat)*7.5) for lon,lat in unwrapped]
                pieces.append('M'+'L'.join(f'{x:.2f},{y:.2f}' for x,y in points)+'Z')
            if pieces: paths.append(''.join(pieces))
target=D.parents[1]/'remotion/src/landPaths.ts'
target.write_text('// Generated by assets/map/convert.py; Natural Earth public domain.\n'
    +f'export const LAND_SOURCE_SHA256={json.dumps(hashlib.sha256(raw).hexdigest())};\n'
    +'export const LAND_PATHS: readonly string[]='+json.dumps(paths,separators=(',',':'))+';\n')
print('Projected',len(paths),'land polygons; source',hashlib.sha256(raw).hexdigest())
